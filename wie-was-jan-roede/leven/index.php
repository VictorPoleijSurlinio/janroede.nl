                <h1>Leven</h1>
                <p><strong>Jan Roëde (1914-2007)</strong> was een van de meest opmerkelijke naoorlogse moderne kunstenaars in Den Haag. Hij was onder andere nauw betrokken bij de roemruchte Posthoorngroep. Roëde was een veelzijdig talent; hij maakte schilderijen, tekeningen, grafiek en gouaches, maar ontwierp ook illustraties, glaskunstwerken en wandschilderingen.</p>

                <h2>Jeugd en opleiding in Den Haag</h2>
                <p>Jan Roede (oorspronkelijk zonder trema) werd op 13 juni 1914 geboren in Groningen. Vanaf zijn vierde jaar groeide hij op in Den Haag. Hier bleef hij - afgezien van enkele periodes in het buitenland - zijn hele leven wonen en werken.</p>
                <p>Zijn artistieke basis legde hij aan de Haagse Koninklijke Academie van Beeldende Kunsten (KABK). Hij volgde hier in 1930-1931 een opleiding tot tekenleraar, gevolgd door een tekenstudie en een avondopleiding reclametekenen bij de bekende ontwerpgrootheden Gerrit Kiljan en Paul Schuitema.</p>

                <h2>Grafisch werk en de stap naar het canvas</h2>
                <p>Van 1933 tot in de vroege jaren zestig werkte Roëde als freelance grafisch ontwerper en illustrator voor boeken en reclames. Dit illustratiewerk vormde de basis voor het sterke, herkenbare tekenhandschrift dat later ook in zijn schilderijen terugkeerde. Bekijk ook <a href="<?= SITE_URL ?>wie-was-jan-roede/de-ontwerper-en-illustrator-jan-roede">De ontwerper en illustrator Jan Roëde</a>.</p>
                <p>In 1941 stimuleerden collega-kunstenaars Willem Hussem en Arnold Smith hem om te gaan schilderen. Vanaf dat moment verdiepte hij zich volledig in de schilderkunst en de literatuur.</p>

                <h2>Inspiratie en het Zenboeddhisme</h2>
                <p>Tijdens zijn vroege kunstenaarschap maakte Roëde kennis met het Zenboeddhisme. Deze levensvisie inspireerde hem de rest van zijn leven diep. Vooral de onafhankelijke kijk op het leven sprak hem aan: <em>"Je moet naar eigen wijsheid handelen"</em>, zo stelde hij zelf.</p>
                <p>Roëde schilderde puur intuïtief. Hij zag zijn beste werken als 'relikwieën van een verlicht moment': kunstwerken die tijdloos, onbevangen en volledig bevrijd zijn van de dressuur van het denken.</p>

                <h2>Internationale doorbraak en Parijse invloeden (1945-1948)</h2>
                <p>Eind 1945 beleefde Roëde zijn eerste tentoonstelling bij de Haagse Kunsthandel Liernur. Zijn werk viel direct op bij Willy Broers (de latere oprichter van de kunstenaarsgroepen <em>Vrije Beelden</em> en <em>Creatie</em>). Broers nodigde hem uit voor de invloedrijke tentoonstelling <em>'12 Schilders'</em> in het Stedelijk Museum Amsterdam in 1946.</p>
                <p>Tussen 1946 en 1948 verbleef Roëde afwisselend in Zweden en Frankrijk, waar hij veel succes oogstte met solotentoonstellingen. Omdat de Fransen zijn achternaam moeilijk konden uitspreken, voegde hij vanaf 1946 het trema toe en werkte hij vanaf dat moment onder de naam Roëde.</p>
                <p>In Parijs raakte hij via dichter Paul Éluard geïnspireerd door het surrealisme. Éluard schonk hem een exemplaar van zijn bundel <em>Facile</em> met de handgeschreven opdracht: <em>'Jan Roëde qui sait la couleur'</em> (Jan Roëde die de kleur kent). [link: naar de via deze website toegankelijke pagina: Jan Roëde over zijn vriendschap met Paul Éluard] Ook ontmoette hij de <em>Jeunes Peintres de Tradition Française</em>. Bij schilder Maurice Estève ontdekte hij in 1948 het 'omgekeerd kleurenperspectief' (koele kleuren op de voorgrond, warme kleuren op de achtergrond). Deze techniek werd een belangrijk kenmerk van zijn latere werk.</p>

                <h2>Een eigen koers: De keuze tegen Cobra</h2>
                <p>Hoewel zijn werk in die tijd verwantschap toonde met Cobra (beïnvloed door Klee, Miró en Picasso), sloeg hij een uitnodiging om zich bij deze groep aan te sluiten af. Het fanatieke idealisme en het schrijven van pamfletten pasten niet bij hem. Wel bleef hij exposeren bij <em>Vrije Beelden</em> en nam hij in 1950 deel aan de grote tentoonstelling <em>Nieuwe bewegingen in de beeldende kunst</em> in het Stedelijk Museum.</p>

                <h2>Terug in Den Haag en artistieke evolutie</h2>
                <p>In 1948 vestigde Roëde zich weer in Den Haag en ontwikkelde hij zich tot een verrassende colorist met een unieke, eigen stijl. Speels en met een glimlach schilderde hij eenvoudige mens- en dierfiguren in niet-naturalistische kleuren. Vanaf de tweede helft van de jaren 60 werd zijn kleurgebruik feller en egaler.</p>
                <p>Roëde was tot het einde van zijn leven actief lid van Pulchri Studio en van de Haagse Kunstkring. In 1968 won hij de prestigieuze Jacob Hartogprijs.</p>

                <h2>Belangrijke overzichtstentoonstellingen</h2>
                <p>Zijn status als topkunstenaar werd bevestigd door diverse grote museale exposities, zoals de overzichtstentoonstellingen in het Gemeentemuseum Den Haag (1968 en 1988), de spraakmakende groepsexpositie over de doorbraak van de moderne kunst in Leiden (De Lakenhal) en andere steden in 1984 en de solotentoonstelling <em>'Jan Roëde. Een kunstenaar keert terug tot zijn middelpunt'</em> in het Cobra Museum (Amstelveen).</p>

                <h2>Persoonlijk leven</h2>
                <p>Jan Roëde was getrouwd met Maria Barbara Leewens (1913-1997). Samen kregen zij twee kinderen: Jan (1941-1998) en Marjolijn (1943-2008). De kunstenaar overleed op 30 mei 2007 op 92-jarige leeftijd.</p>
